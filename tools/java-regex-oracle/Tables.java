import java.io.IOException;
import java.lang.reflect.Field;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashMap;
import java.util.Map;
import java.util.TreeMap;

/**
 * Writes the Rust tables of the Unicode block and script names that {@code \p{InBlock}},
 * {@code \p{block=...}}, {@code \p{IsScript}}, and {@code \p{script=...}} accept, read from
 * {@code java.lang.Character}. Needs {@code --add-opens java.base/java.lang=ALL-UNNAMED} to read
 * the private name maps.
 */
public final class Tables {
    public static void main(String[] args) throws IOException, ReflectiveOperationException {
        if (args.length != 1) {
            System.err.println("usage: Tables <out.rs>");
            System.exit(2);
        }
        StringBuilder out = new StringBuilder();
        out.append("//! Unicode block and script names as `java.lang.Character` defines them (JDK ")
                .append(Runtime.version().feature()).append(").\n//!\n")
                .append("//! Generated by `tools/java-regex-oracle/tables.sh`; do not edit.\n\n");
        int blocks = blocks(out);
        int scripts = scripts(out);
        Files.writeString(Path.of(args[0]), out.toString(), StandardCharsets.UTF_8);
        System.err.println("java " + System.getProperty("java.version") + ": wrote " + blocks
                + " block names and " + scripts + " script names");
    }

    private static int blocks(StringBuilder out) throws ReflectiveOperationException {
        Map<Character.UnicodeBlock, int[]> ranges = new HashMap<>();
        for (int cp = 0; cp <= Character.MAX_CODE_POINT; cp++) {
            Character.UnicodeBlock block = Character.UnicodeBlock.of(cp);
            if (block == null) {
                continue;
            }
            int[] range = ranges.computeIfAbsent(block, b -> new int[] {Integer.MAX_VALUE, -1});
            range[0] = Math.min(range[0], cp);
            range[1] = Math.max(range[1], cp);
        }
        Map<String, Character.UnicodeBlock> names = privateMap(Character.UnicodeBlock.class, "map");
        TreeMap<String, int[]> sorted = new TreeMap<>();
        for (Map.Entry<String, Character.UnicodeBlock> entry : names.entrySet()) {
            int[] range = ranges.getOrDefault(entry.getValue(), new int[] {1, 0});
            for (int cp = range[0]; cp <= range[1]; cp++) {
                if (Character.UnicodeBlock.of(cp) != entry.getValue()) {
                    throw new IllegalStateException("block " + entry.getKey() + " is not contiguous");
                }
            }
            sorted.put(entry.getKey(), range);
        }
        out.append("/// Every name `UnicodeBlock.forName` accepts, in upper case and sorted, with the block's\n")
                .append("/// first and last code point. A block without code points has `first > last`.\n")
                .append("#[rustfmt::skip]\n")
                .append("pub(crate) const BLOCKS: &[(&str, u32, u32)] = &[\n");
        for (Map.Entry<String, int[]> entry : sorted.entrySet()) {
            out.append("    (\"").append(entry.getKey()).append("\", ")
                    .append(hex(entry.getValue()[0])).append(", ")
                    .append(hex(entry.getValue()[1])).append("),\n");
        }
        out.append("];\n\n");
        return sorted.size();
    }

    private static int scripts(StringBuilder out) throws ReflectiveOperationException {
        TreeMap<String, String> sorted = new TreeMap<>();
        for (Character.UnicodeScript script : Character.UnicodeScript.values()) {
            sorted.put(script.name(), script.name());
        }
        Map<String, Character.UnicodeScript> aliases =
                privateMap(Character.UnicodeScript.class, "aliases");
        for (Map.Entry<String, Character.UnicodeScript> entry : aliases.entrySet()) {
            sorted.put(entry.getKey(), entry.getValue().name());
        }
        out.append("/// Every name `UnicodeScript.forName` accepts, in upper case and sorted, with the\n")
                .append("/// script's constant name.\n")
                .append("#[rustfmt::skip]\n")
                .append("pub(crate) const SCRIPTS: &[(&str, &str)] = &[\n");
        for (Map.Entry<String, String> entry : sorted.entrySet()) {
            out.append("    (\"").append(entry.getKey()).append("\", \"")
                    .append(entry.getValue()).append("\"),\n");
        }
        out.append("];\n");
        return sorted.size();
    }

    @SuppressWarnings("unchecked")
    private static <T> Map<String, T> privateMap(Class<?> owner, String name)
            throws ReflectiveOperationException {
        Field field = owner.getDeclaredField(name);
        field.setAccessible(true);
        return (Map<String, T>) field.get(null);
    }

    private static String hex(int value) {
        String digits = Integer.toHexString(value).toUpperCase();
        if (digits.length() <= 4) {
            return "0x" + "0000".substring(digits.length()) + digits;
        }
        int split = digits.length() - 4;
        return "0x" + digits.substring(0, split) + "_" + digits.substring(split);
    }
}
